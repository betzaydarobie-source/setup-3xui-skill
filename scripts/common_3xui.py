def strip_ansi(text: str) -> str:
    return ANSI_RE.sub("", text)


def require_password() -> str:
    password = os.environ.get("VPS_PASSWORD") or os.environ.get("SSH_PASSWORD")
    if not password:
        raise SystemExit("Set VPS_PASSWORD in the environment before running this script.")
    return password


def random_token(length: int = 16) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


def expect_ssh(
    *,
    host: str,
    user: str,
    ssh_port: int,
    password: str,
    remote_command: str,
    timeout: int = 1200,
) -> subprocess.CompletedProcess[str]:
    known_hosts = f"/tmp/codex_3xui_known_hosts_{host.replace('.', '_')}_{os.getpid()}"
    expect_script = f"""
set timeout {timeout}
spawn ssh -tt -o StrictHostKeyChecking=no -o UserKnownHostsFile={known_hosts} -p {ssh_port} {user}@{host} {json.dumps(remote_command)}
expect {{
  -re {{password:}} {{ send "$env(VPS_PASSWORD)\\r"; exp_continue }}
  -re {{Please enter your server.*public IPv4 address:}} {{ send "{host}\\r"; exp_continue }}
  -re {{Choose \\[1\\]:}} {{ send "\\r"; exp_continue }}
  -re {{Would you like to customize the Panel Port settings\\?}} {{ send "y\\r"; exp_continue }}
  -re {{Please set up the panel port:}} {{ send "$env(PANEL_PORT)\\r"; exp_continue }}
  -re {{Choose an option \\(default 2 for IP\\):}} {{ send "\\r"; exp_continue }}
  -re {{Do you have an IPv6 address to include\\?}} {{ send "\\r"; exp_continue }}
  -re {{Port to use for ACME HTTP-01 listener.*:}} {{ send "\\r"; exp_continue }}
  -re {{Enter another port for acme\\.sh standalone listener.*:}} {{ send "\\r"; exp_continue }}
  timeout {{ puts "\\nEXPECT_TIMEOUT"; exit 124 }}
  eof
}}
catch wait result
exit [lindex $result 3]
"""
    env = os.environ.copy()
    env["VPS_PASSWORD"] = password
    return subprocess.run(
        ["expect", "-c", expect_script],
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )


def optimize_network(
    *,
    host: str,
    user: str,
    ssh_port: int,
    password: str,
    timeout: int = 120,
) -> subprocess.CompletedProcess[str]:
    """Apply BBR + TCP/memory/fd tuning on the VPS via an idempotent sysctl drop-in.

    Ships NETWORK_SYSCTL as base64 so multi-line content survives the
    repr -> json.dumps -> Tcl -> remote-shell quoting chain without any escaping
    surprises, then reloads sysctl and loads the bbr/fq modules. Re-running it
    just rewrites the same drop-in file, so it is safe to call repeatedly.
    """
    payload = base64.b64encode(NETWORK_SYSCTL.encode("utf-8")).decode("ascii")
    # Order matters: load the bbr/fq modules BEFORE applying sysctl. On stock
    # Ubuntu kernels tcp_bbr is not preloaded (tcp_available_congestion_control
    # shows only "reno cubic"), so applying `tcp_congestion_control = bbr` first
    # could fail. modprobe first guarantees bbr is available when sysctl sets it.
    remote_command = "bash -lc " + repr(
        f"echo '{payload}' | base64 -d > /etc/sysctl.d/99-xray-optimization.conf; "
        "modprobe tcp_bbr >/dev/null 2>&1 || true; "
        "modprobe sch_fq >/dev/null 2>&1 || true; "
        "sysctl --system >/dev/null 2>&1 || "
        "sysctl -p /etc/sysctl.d/99-xray-optimization.conf >/dev/null 2>&1 || true; "
        "echo '----- optimization result -----'; "
        "sysctl net.ipv4.tcp_congestion_control net.core.default_qdisc net.ipv4.tcp_fastopen 2>/dev/null || true; "
        "(lsmod | grep -q '^tcp_bbr' && echo 'tcp_bbr module: loaded') "
        "|| echo 'tcp_bbr module: builtin or unavailable'"
    )
    return expect_ssh(
        host=host,
        user=user,
        ssh_port=ssh_port,
        password=password,
        remote_command=remote_command,
        timeout=timeout,
    )


def deploy_karing_adapter(
    *,
    host: str,
    user: str,
    ssh_port: int,
    password: str,
    session: "PanelSession",
    public_host: str | None = None,
    listen_port: int = 2097,
    timeout: int = 180,
) -> dict[str, Any]:
    """Install the Karing-compatibility subscription adapter and point the panel at it.

    Deploys KARING_ADAPTER_PY as a systemd service on :listen_port (default 2097) in front
    of the 3X-UI sub server (:subPort, default 2096), enables the sub server, and sets
    subURI/subClashURI so the panel hands out :listen_port subscription URLs for every
    client (add_3xui_client.py then emits :listen_port links automatically).

    SAFETY: the adapter owns listen_port; the panel's subPort stays UNCHANGED. NEVER set
    subPort to listen_port -- that collides with the adapter and crash-loops x-ui (which
    drops xray :443 and disconnects customers). Deploying the adapter does not touch xray;
    only the subEnable/subURI DB edit needs a brief x-ui restart (safe on a fresh install).
    Ships everything base64-encoded through the same Tcl-safe path as optimize_network.
    Returns a result dict and never raises; a failed adapter must not fail the install.
    """
    public_host = (public_host or host).strip() or host

    # 1) Read live sub settings so the adapter is templated to THIS panel.
    #    3X-UI 3.4.x moved the settings API under /panel/api/setting/all; older
    #    panels (<=3.2.x) serve it at /panel/setting/all. Try the new path first
    #    and fall back, so the adapter deploys on both.
    settings: dict[str, Any] = {}
    last_exc: Exception | None = None
    for _ep in ("/panel/api/setting/all", "/panel/setting/all"):
        try:
            st = session.post_form(_ep)
        except Exception as exc:
            last_exc = exc
            continue
        if isinstance(st, dict) and st.get("success"):
            settings = st.get("obj") or {}
            break
    else:
        return {"deployed": False, "error": f"could not read panel settings: {last_exc!r}"}

    upstream_port = int(settings.get("subPort") or 2096)
    if listen_port == upstream_port:
        listen_port = upstream_port + 1  # never collide with the sub server
    sub_path = settings.get("subPath") or "/sub/"
    clash_path = settings.get("subClashPath") or "/clash/"
    cert_file = settings.get("subCertFile") or settings.get("webCertFile") or "/root/cert/ip/fullchain.pem"
    key_file = settings.get("subKeyFile") or settings.get("webKeyFile") or "/root/cert/ip/privkey.pem"

    def _as_uri(path: str) -> str:
        p = path if path.startswith("/") else "/" + path
        uri = f"https://{public_host}:{listen_port}{p}"
        return uri if uri.endswith("/") else uri + "/"

    sub_uri = _as_uri(sub_path)
    clash_uri = _as_uri(clash_path)

    # 2) Template the adapter for this panel (RAW-string placeholders -> real values).
    adapter_py = (
        KARING_ADAPTER_PY
        .replace("__LISTEN_PORT__", str(listen_port))
        .replace("__UPSTREAM_PORT__", str(upstream_port))
        .replace("__CERT_FILE__", cert_file)
        .replace("__KEY_FILE__", key_file)
    )

    # 3) DB edit: enable the sub server + advertise the adapter. Only fill cert/key when
    #    the panel has none, so a working cert path is never clobbered.
    pairs: list[tuple[str, str]] = [
        ("subEnable", "true"),
        ("subURI", sub_uri),
        ("subClashURI", clash_uri),
    ]
    if not settings.get("subCertFile"):
        pairs.append(("subCertFile", cert_file))
    if not settings.get("subKeyFile"):
        pairs.append(("subKeyFile", key_file))
    edit_script = (
        "import sqlite3\n"
        "DB = '/etc/x-ui/x-ui.db'\n"
        f"PAIRS = {pairs!r}\n"
        "con = sqlite3.connect(DB, timeout=20)\n"
        "cur = con.cursor()\n"
        "for k, v in PAIRS:\n"
        "    cur.execute('UPDATE settings SET value=? WHERE key=?', (v, k))\n"
        "    if cur.rowcount == 0:\n"
        "        cur.execute('INSERT INTO settings (key,value) VALUES (?,?)', (k, v))\n"
        "con.commit()\n"
        "rows = [list(r) for r in cur.execute(\"SELECT key,value FROM settings WHERE key IN ('subEnable','subURI','subClashURI')\").fetchall()]\n"
        "print('KARING_DB_OK', rows)\n"
        "con.close()\n"
    )

    py_b64 = base64.b64encode(adapter_py.encode("utf-8")).decode("ascii")
    svc_b64 = base64.b64encode(KARING_ADAPTER_SERVICE.encode("utf-8")).decode("ascii")
    edit_b64 = base64.b64encode(edit_script.encode("utf-8")).decode("ascii")

    # 4) One Tcl/bash-safe remote orchestration (base64 blobs + single-quoted patterns;
    #    no $ [ ] backtick backslash). Deploy adapter -> enable+start -> open ufw if active
    #    -> stop x-ui, back up db, enable sub + set subURI, start x-ui -> verify ports.
    lp = str(listen_port)
    up = str(upstream_port)
    hc_url = "https://127.0.0.1:" + lp + "/" + sub_path.strip("/") + "/healthcheck"
    cmd = (
        "echo '" + py_b64 + "' | base64 -d > /usr/local/bin/karing-sub-adapter.py; "
        "chmod +x /usr/local/bin/karing-sub-adapter.py; "
        "echo '" + svc_b64 + "' | base64 -d > /etc/systemd/system/karing-sub-adapter.service; "
        "echo '" + edit_b64 + "' | base64 -d > /tmp/karing_set_sub.py; "
        "echo '== CERT =='; (test -f '" + cert_file + "' && test -f '" + key_file + "' && echo CERT_OK || echo CERT_MISSING); "
        "systemctl daemon-reload; "
        "systemctl enable karing-sub-adapter >/dev/null 2>&1; "
        "systemctl restart karing-sub-adapter; "  # restart (not just start) so a re-run reloads the fresh file
        "(ufw status 2>/dev/null | grep -qi 'status: active' && ufw allow " + lp + "/tcp >/dev/null 2>&1 && echo UFW_OPENED || echo UFW_SKIP); "
        "sleep 2; "
        "echo '== set subURI (brief x-ui restart) =='; "
        "systemctl stop x-ui; "
        "cp /etc/x-ui/x-ui.db /etc/x-ui/x-ui.db.bak-karing-adapter; "
        "python3 /tmp/karing_set_sub.py; "
        "systemctl start x-ui; "
        "sleep 4; "
        "echo '== adapter active =='; systemctl is-active karing-sub-adapter; "
        "echo '== x-ui active =='; systemctl is-active x-ui; "
        "echo '== adapter port =='; (ss -ltn 2>/dev/null | grep ':" + lp + "' || echo ADAPTER_PORT_DOWN); "
        "echo '== sub port =='; (ss -ltn 2>/dev/null | grep ':" + up + "' || echo SUB_PORT_DOWN); "
        "echo '== healthcheck =='; curl -k -sI " + hc_url + " 2>&1 | head -1"
    )
    remote_command = "bash -lc " + repr(cmd)
    res = expect_ssh(
        host=host, user=user, ssh_port=ssh_port, password=password,
        remote_command=remote_command, timeout=timeout,
    )
    out = res.stdout or ""
    # expect echoes the FULL spawned command (which literally contains our CERT_OK /
    # ADAPTER_PORT_DOWN / UFW_OPENED markers as echo arguments) on its "spawn ssh ..."
    # line. Strip that line so each marker is detected only where the remote shell
    # actually printed it, not where it merely appears inside the command text.
    scan = "\n".join(ln for ln in out.splitlines() if not ln.lstrip().startswith("spawn "))

    cert_ok = "CERT_OK" in scan
    db_ok = "KARING_DB_OK" in scan
    adapter_port_up = "ADAPTER_PORT_DOWN" not in scan
    sub_port_up = "SUB_PORT_DOWN" not in scan
    return {
        "deployed": res.returncode == 0 and cert_ok and db_ok and adapter_port_up and sub_port_up,
        "listenPort": listen_port,
        "upstreamPort": upstream_port,
        "subURI": sub_uri,
        "subClashURI": clash_uri,
        "certFile": cert_file,
        "keyFile": key_file,
        "certPresent": cert_ok,
        "subEnabled": db_ok,
        "adapterPortListening": adapter_port_up,
        "subPortListening": sub_port_up,
        "ufwOpened": "UFW_OPENED" in scan,
        "dbBackup": "/etc/x-ui/x-ui.db.bak-karing-adapter",
        "log": out,
    }


def parse_panel_install_log(log_text: str) -> dict[str, Any]:
    clean = strip_ansi(log_text)
    patterns = {
        "username": r"Username:\s*([^\s]+)",
        "password": r"Password:\s*([^\s]+)",
        "port": r"Port:\s*([0-9]+)",
        "web_base_path": r"WebBasePath:\s*([^\s]+)",
        "access_url": r"Access URL:\s*(https?://[^\s]+)",
        "api_token": r"API Token:\s*([^\s]+)",
        "database": r"Database:\s*(.+)",
    }
    info: dict[str, Any] = {}
    for key, pattern in patterns.items():
        match = re.search(pattern, clean)
        if match:
            info[key] = match.group(1).strip()
    if "port" in info:
        info["port"] = int(info["port"])
    if "web_base_path" in info:
        path = info["web_base_path"]
        info["web_base_path"] = "/" + path.strip("/") + "/"
    required = ["username", "password", "port", "web_base_path", "access_url"]
    missing = [key for key in required if not info.get(key)]
    if missing:
        raise ValueError(f"Could not parse panel install log. Missing: {', '.join(missing)}")
    return info


class PanelSession:
    def __init__(self, base_url: str, username: str, password: str) -> None:
        self.base_url = base_url.rstrip("/")
        self.username = username
        self.password = password
        self.cookiejar = http.cookiejar.CookieJar()
        self.opener = urllib.request.build_opener(
            urllib.request.HTTPSHandler(context=ssl._create_unverified_context()),
            urllib.request.HTTPCookieProcessor(self.cookiejar),
        )
        self.csrf_token = ""

    def _request(
        self,
        method: str,
        path: str,
        data: Any | None = None,
        *,
        json_body: bool = False,
        csrf: bool = False,
    ) -> Any:
        url = self.base_url + path
        body = None
        headers = {"X-Requested-With": "XMLHttpRequest"}
        if csrf and self.csrf_token:
            headers["X-CSRF-Token"] = self.csrf_token
        if data is not None:
            if json_body:
                body = json.dumps(data).encode("utf-8")
                headers["Content-Type"] = "application/json"
            else:
                body = urllib.parse.urlencode(data).encode("utf-8")
                headers["Content-Type"] = "application/x-www-form-urlencoded; charset=UTF-8"
        req = urllib.request.Request(url, data=body, headers=headers, method=method)
        with self.opener.open(req, timeout=45) as resp:
            text = resp.read().decode("utf-8", "replace")
            ctype = resp.headers.get("content-type", "")
        if "json" in ctype or text.startswith("{") or text.startswith("["):
            return json.loads(text)
        return text

    def login(self) -> None:
        html_text = self._request("GET", "/")
        match = re.search(r'name="csrf-token" content="([^"]+)"', html_text)
        if match:
            self.csrf_token = match.group(1)
        result = self._request(
            "POST",
            "/login",
            {"username": self.username, "password": self.password},
            csrf=True,
        )
        if not isinstance(result, dict) or not result.get("success"):
            raise RuntimeError(f"3X-UI login failed: {result}")
        try:
            token = self._request("GET", "/csrf-token")
            if isinstance(token, dict) and token.get("success") and token.get("obj"):
                self.csrf_token = token["obj"]
        except Exception:
            pass

    def get(self, path: str) -> Any:
        return self._request("GET", path)

    def post_form(self, path: str, data: dict[str, Any] | None = None) -> Any:
        return self._request("POST", path, data or {}, csrf=True)

    def post_json(self, path: str, data: dict[str, Any] | list[Any] | None = None) -> Any:
        return self._request("POST", path, data or {}, json_body=True, csrf=True)


def load_panel_info(path: Path) -> dict[str, Any]:
    info = json.loads(path.read_text(encoding="utf-8"))
    panel = info.get("panel", info)
    for key in ["url", "username", "password"]:
        if not panel.get(key):
            raise ValueError(f"panel-info JSON missing panel.{key}")
    return info


def panel_session_from_info(info: dict[str, Any]) -> PanelSession:
    panel = info.get("panel", info)
    session = PanelSession(panel["url"], panel["username"], panel["password"])
    session.login()
    return session


