# Karing-compatibility subscription adapter. The stock 3X-UI sub server (1) returns 404
# to HEAD requests, which breaks Karing's "check for update" (it shows 更新失败 404), and
# (2) emits `packet-encoding: none` in its Clash YAML, which some Karing builds reject.
# This tiny stdlib reverse proxy sits in front of the sub server: it always GETs upstream
# (so HEAD gets a real status), forwards the client Host (so each node resolves to the real
# server, not 127.0.0.1), and strips packet-encoding from /clash/. The four __PLACEHOLDER__
# values are substituted by deploy_karing_adapter() for the specific panel. RAW string so
# the embedded \n \t \r stay literal in the generated file.
KARING_ADAPTER_PY = r'''#!/usr/bin/env python3
"""Karing-compatibility subscription adapter for 3X-UI (generated by setup-3xui)."""
import http.client
import re
import ssl
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

LISTEN_HOST = "0.0.0.0"
LISTEN_PORT = __LISTEN_PORT__
UPSTREAM_HOST = "127.0.0.1"
UPSTREAM_PORT = __UPSTREAM_PORT__
CERT_FILE = "__CERT_FILE__"
KEY_FILE = "__KEY_FILE__"

# Response headers worth passing back so clients still show traffic/expiry/update info.
PASS_RESP_HEADERS = (
    "content-type",
    "subscription-userinfo",
    "profile-update-interval",
    "profile-title",
    "profile-web-page-url",
    "content-disposition",
)
PACKET_ENCODING_RE = re.compile(rb"^[ \t]*packet-encoding:[ \t]*none[ \t]*\r?\n", re.MULTILINE)

_upstream_ctx = ssl._create_unverified_context()


class Handler(BaseHTTPRequestHandler):
    server_version = "karing-sub-adapter/1.0"
    protocol_version = "HTTP/1.1"

    def _proxy(self):
        # Always GET upstream (upstream 404s on HEAD); shape the response afterwards.
        try:
            conn = http.client.HTTPSConnection(
                UPSTREAM_HOST, UPSTREAM_PORT, timeout=20, context=_upstream_ctx
            )
            # 3X-UI derives each node's address from the request Host header, so the
            # client's Host must reach upstream unchanged; otherwise nodes come back
            # pointing at the adapter's 127.0.0.1 upstream instead of the real server.
            fwd = {}
            for h in ("Host", "User-Agent", "Accept"):
                v = self.headers.get(h)
                if v:
                    fwd[h] = v
            conn.request("GET", self.path, headers=fwd)
            resp = conn.getresponse()
            body = resp.read()
            status = resp.status
            resp_headers = resp.getheaders()
            conn.close()
        except Exception as exc:  # never crash the worker on a bad upstream
            sys.stderr.write("[adapter] upstream error: %r\n" % (exc,))
            try:
                self.send_error(502, "upstream error")
            except Exception:
                pass
            return

        # Fix #2: strip the Karing-incompatible Clash field.
        if "/clash" in self.path.lower():
            body = PACKET_ENCODING_RE.sub(b"", body)

        # Fix #1: HEAD always answers with upstream status (with Content-Length, no body).
        self.send_response(status)
        for k, v in resp_headers:
            if k.lower() in PASS_RESP_HEADERS:
                self.send_header(k, v)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def do_GET(self):
        self._proxy()

    def do_HEAD(self):
        self._proxy()

    def log_message(self, fmt, *args):
        sys.stderr.write("[adapter] " + (fmt % args) + "\n")


def main():
    httpd = ThreadingHTTPServer((LISTEN_HOST, LISTEN_PORT), Handler)
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(CERT_FILE, KEY_FILE)
    httpd.socket = ctx.wrap_socket(httpd.socket, server_side=True)
    sys.stderr.write(
        "[adapter] listening on %s:%d -> %s:%d\n"
        % (LISTEN_HOST, LISTEN_PORT, UPSTREAM_HOST, UPSTREAM_PORT)
    )
    httpd.serve_forever()


if __name__ == "__main__":
    main()
'''


